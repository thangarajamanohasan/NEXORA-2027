-- NEXORA 2027. Run once in Supabase SQL Editor.
-- Student IDs are permanent and never reused. Seats can be reused after cancellation.
create extension if not exists pgcrypto;
create sequence if not exists public.nexora_student_id_seq start 1 increment 1 minvalue 1 maxvalue 999999 no cycle;

create table if not exists public.profiles(
 id uuid primary key references auth.users(id) on delete cascade,
 role text not null default 'student' check(role in('student','admin')),
 full_name text not null,
 student_id text unique not null,
 created_at timestamptz not null default now()
);
create table if not exists public.seats(
 id smallint generated by default as identity primary key,
 seat_number text unique not null,
 is_booked boolean not null default false
);
insert into public.seats(seat_number)
select 'NXR-SEAT-'||lpad(n::text,3,'0') from generate_series(1,250)n
on conflict(seat_number) do nothing;

create table if not exists public.registrations(
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null unique references auth.users(id) on delete restrict,
 student_id text not null unique references public.profiles(student_id),
 full_name text not null,dob date not null,nic text not null unique,address text not null,
 whatsapp_number text not null,mobile_number text not null,
 seat_id smallint references public.seats(id),seat_number text,
 status text not null default 'confirmed' check(status in('confirmed','cancelled')),
 qr_token uuid not null unique default gen_random_uuid(),
 created_at timestamptz not null default now(),cancelled_at timestamptz
);
create index if not exists registrations_status_idx on public.registrations(status);
-- A seat may appear in historical cancelled rows, but only one active booking may hold it.
create unique index if not exists registrations_active_seat_id_uidx
on public.registrations(seat_id) where status='confirmed';
create unique index if not exists registrations_active_seat_number_uidx
on public.registrations(seat_number) where status='confirmed';

create or replace function public.handle_new_nexora_user()
returns trigger language plpgsql security definer set search_path=''
as $$
declare n bigint;
begin
 n:=nextval('public.nexora_student_id_seq');
 insert into public.profiles(id,role,full_name,student_id)
 values(new.id,'student',coalesce(nullif(trim(new.raw_user_meta_data->>'full_name'),''),'NEXORA Student'),'NXR2027-'||lpad(n::text,6,'0'));
 return new;
end;$$;
drop trigger if exists on_auth_user_created_nexora on auth.users;
create trigger on_auth_user_created_nexora after insert on auth.users
for each row execute function public.handle_new_nexora_user();

create schema if not exists private;
create or replace function private.is_nexora_admin()
returns boolean language sql stable security definer set search_path=''
as $$ select exists(select 1 from public.profiles where id=(select auth.uid()) and role='admin'); $$;
revoke all on function private.is_nexora_admin() from public;
grant usage on schema private to authenticated;
grant execute on function private.is_nexora_admin() to authenticated;

alter table public.profiles enable row level security;
alter table public.seats enable row level security;
alter table public.registrations enable row level security;
revoke all on public.profiles,public.seats,public.registrations from anon,authenticated;
grant select on public.profiles,public.registrations to authenticated;

create policy "profile owner or admin reads" on public.profiles for select to authenticated
using(id=(select auth.uid()) or (select private.is_nexora_admin()));
create policy "registration owner or admin reads" on public.registrations for select to authenticated
using(user_id=(select auth.uid()) or (select private.is_nexora_admin()));
create policy "admin updates profiles" on public.profiles for update to authenticated
using((select private.is_nexora_admin())) with check((select private.is_nexora_admin()));

create or replace function public.get_seat_summary()
returns jsonb language sql stable security definer set search_path=''
as $$ select jsonb_build_object('total',count(*)::int,'booked',count(*)filter(where is_booked)::int,'available',count(*)filter(where not is_booked)::int) from public.seats; $$;
revoke all on function public.get_seat_summary() from public;
grant execute on function public.get_seat_summary() to anon,authenticated;

-- Row lock + SKIP LOCKED makes concurrent requests allocate distinct seats safely.
create or replace function public.complete_student_registration(p_dob date,p_nic text,p_address text,p_whatsapp text,p_mobile text)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare uid uuid:=auth.uid(); prof public.profiles%rowtype; s public.seats%rowtype; r public.registrations%rowtype;
begin
 if uid is null then raise exception 'Please sign in first.'; end if;
 select * into prof from public.profiles where id=uid;
 if not found or prof.role<>'student' then raise exception 'Student account required.'; end if;
 if exists(select 1 from public.registrations where user_id=uid) then raise exception 'This account is already registered.'; end if;
 if length(trim(coalesce(p_nic,'')))<5 or length(trim(coalesce(p_address,'')))<5 then raise exception 'Enter valid NIC and address details.'; end if;
 if length(trim(coalesce(p_whatsapp,'')))<7 or length(trim(coalesce(p_mobile,'')))<7 then raise exception 'Enter valid contact numbers.'; end if;
 select * into s from public.seats where is_booked=false order by id for update skip locked limit 1;
 if not found then raise exception 'All 250 seats have been booked.'; end if;
 update public.seats set is_booked=true where id=s.id;
 insert into public.registrations(user_id,student_id,full_name,dob,nic,address,whatsapp_number,mobile_number,seat_id,seat_number)
 values(uid,prof.student_id,prof.full_name,p_dob,trim(p_nic),trim(p_address),trim(p_whatsapp),trim(p_mobile),s.id,s.seat_number)
 returning * into r;
 return jsonb_build_object('student_id',r.student_id,'seat_number',r.seat_number,'qr_token',r.qr_token,'status',r.status);
exception when unique_violation then raise exception 'A registration already exists for this account or NIC.';
end;$$;
revoke all on function public.complete_student_registration(date,text,text,text,text) from public,anon;
grant execute on function public.complete_student_registration(date,text,text,text,text) to authenticated;

-- QR verification deliberately exposes only ticket details, never NIC/address/contact information.
create or replace function public.verify_qr_token(p_token uuid)
returns jsonb language plpgsql security definer set search_path=''
as $$ declare r public.registrations%rowtype;
begin
 select * into r from public.registrations where qr_token=p_token;
 if not found then raise exception 'Invalid QR code.'; end if;
 if r.status<>'confirmed' then raise exception 'Registration is not active.'; end if;
 return jsonb_build_object('full_name',r.full_name,'student_id',r.student_id,'seat_number',r.seat_number,'status',r.status,'event','NEXORA 2027','event_date','19 January 2027');
end;$$;
revoke all on function public.verify_qr_token(uuid) from public;
grant execute on function public.verify_qr_token(uuid) to anon,authenticated;

create or replace function public.admin_cancel_registration(p_registration_id uuid)
returns void language plpgsql security definer set search_path=''
as $$ declare r public.registrations%rowtype;
begin
 if not private.is_nexora_admin() then raise exception 'Admin permission required.'; end if;
 select * into r from public.registrations where id=p_registration_id for update;
 if not found then raise exception 'Registration not found.'; end if;
 if r.status='cancelled' then return; end if;
 update public.registrations set status='cancelled',cancelled_at=now() where id=p_registration_id;
 if r.seat_id is not null then update public.seats set is_booked=false where id=r.seat_id; end if;
end;$$;
revoke all on function public.admin_cancel_registration(uuid) from public,anon;
grant execute on function public.admin_cancel_registration(uuid) to authenticated;
